--- Проверка настроек уведомителя и его приёмников.
---
--- Настройки пишет программист, и негодная — его ошибка: бросок на строке
--- того, кто настраивал, а не отказ где-то потом. Потом — это обход
--- диагностики: хук `on_issues` зовётся под `pcall`, и строка в сроке
--- напоминания, дошедшая до сравнения, остаётся записью в журнале, а
--- уведомления просто перестают уходить. Приёмнику без адреса то же:
--- его отказ виден только в журнале, на каждом событии.
---
--- Незнакомый ключ — тоже бросок: опечатка в имени настройки иначе молча
--- оставила бы умолчание, и `repeat_afer = 60` напоминал бы раз в час.
---
--- `box.NULL` значит «не задано», как и отсутствие ключа: так приходит
--- пустое значение из YAML и JSON, и необязательные проверки `tnt-must`
--- его пропускают. Оставленный в настройках, он истинен в условии,
--- и `given.timeout or 2` отдал бы клиенту его, а не умолчание, — поэтому
--- его здесь и убирают, а не в каждом `or`.

local must = require('tnt.must')

local Module = {}

--- Проверяет настройки по описанию и отдаёт их копию без пустых значений.
---
--- Бросок называет строку того, кто позвал функцию, позвавшую эту:
--- настройки проверяют `configure` и `new`, а ошибся тот, кто их звал.
--- Звать эту функцию не хвостом: хвостовой вызов снимает кадр со стека,
--- и место съехало бы ещё на кадр выше.
---
--- Копия ещё и отвязывает настройки от таблицы вызывающего: правка её
--- после проверки не доедет до того, что проверено.
---@param given any Настройки как их передали
---@param title string Как настройки называются в отказе
---@param spec table Описание для `must.options`: ключ — запись проверки
---@return table
function Module.checked(given, title, spec)
    must.at(3).options(given, title, spec)

    local present = {}

    for key, value in pairs(given) do
        if value ~= nil then
            present[key] = value
        end
    end

    return present
end

return Module
